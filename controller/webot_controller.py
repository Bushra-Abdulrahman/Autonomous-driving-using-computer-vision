from pathlib import Path

import cv2
import numpy as np
import torch
from vehicle import Driver  # Available inside a Webots vehicle controller
from model import CNNModel


def preprocess(frame):
    frame = cv2.resize(frame, (256, 256))
    frame = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
    frame = frame.astype(np.float32) / 255.0
    return torch.from_numpy(frame.transpose(2, 0, 1)).unsqueeze(0)


def main():
    device = torch.device('cpu')
    model = CNNModel().to(device)
    checkpoint = Path(__file__).with_name('cnn_project.pth')
    model.load_state_dict(torch.load(checkpoint, map_location=device, weights_only=True))
    model.eval()

    driver = Driver()
    timestep = int(driver.getBasicTimeStep())
    camera = driver.getDevice('camera')
    camera.enable(timestep)

    while driver.step() != -1:
        image = camera.getImageArray()
        if image is None:
            continue
        frame = np.asarray(image, dtype=np.uint8)
        with torch.no_grad():
            prediction = model(preprocess(frame).to(device))[0].cpu().numpy()
        steering = float(np.clip(prediction[0], -0.5, 0.5))
        speed = float(np.clip(abs(prediction[1]) * 100.0, 10.0, 80.0))
        driver.setSteeringAngle(steering)
        driver.setCruisingSpeed(speed)


if __name__ == '__main__':
    main()